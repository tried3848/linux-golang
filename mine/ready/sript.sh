Строка 19: Двойные скобки [[ ]] расширенное условие bash
Строка 20: Heredoc << позволяет записать многострочный текст
Строка 21: Переменная $file хранит имя текущего файла
Строка 22: name="${file%.go}" убирает расширение .go
Строка 23: Конец файла
EOF

touch 123.zip
touch 123.tar