#!/bin/bash

mkdir -p bin

for file in *.go; do
    [ -f "$file" ] || continue
    name="${file%.go}"
    go build -o "$name" "$file"
done

for fil in *; do
    if [ -f "$fil" ] && [[ "$fil" != *.go ]] && [[ "$fil" != *.sh ]]; then
        mv "$fil" bin/
    fi
done

cd bin

# Наполняем qwe.txt 20-25 строками
cat > qwe.txt << 'EOF'
Строка 1: Привет, это тестовый файл
Строка 2: Используется для проверки скрипта
Строка 3: Go — компилируемый язык программирования
Строка 4: Bash — командный интерпретатор Unix
Строка 5: Файловая система хранит данные на диске
Строка 6: Переменные в bash объявляются без типов
Строка 7: Цикл for позволяет перебирать файлы
Строка 8: Команда mkdir создаёт директории
Строка 9: Команда mv перемещает файлы
Строка 10: Команда touch создаёт пустые файлы
Строка 11: Скрипты bash начинаются с #!/bin/bash
Строка 12: Go build компилирует исходный код
Строка 13: Бинарные файлы хранятся в папке bin
Строка 14: Расширение .go у файлов исходного кода Go
Строка 15: Расширение .sh у файлов bash-скриптов
Строка 16: Команда cd меняет текущую директорию
Строка 17: Флаг -p у mkdir не выдаёт ошибку если папка есть
